# P2 motor; power3=100%. PC4 shortpress runs/stops; RAM only.
import klq
klq.motor_power(3)
klq.wait(2)
klq.display_number(1)
klq.motor_for(2, 1, 0.8)
klq.display_number(0)
klq.wait(0.6)
klq.display_number(2)
klq.motor_for(2, -1, 0.8)
klq.display_number(0)
klq.wait(0.6)
klq.display_number(3)
klq.motor_run(2, 1)
klq.wait(0.8)
klq.motor_stop(2)
klq.display_number(0)
klq.wait(0.6)
klq.display_number(4)
klq.motor_run(2, -1)
klq.wait(0.8)
klq.motor_stop(2)
klq.display_number(0)
klq.wait(0.6)
klq.motor_power(2)
klq.stop()
