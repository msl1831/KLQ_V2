#ifndef KLQ_PROTOCOL_H
#define KLQ_PROTOCOL_H

#include <stdint.h>

#define KLQ_MAGIC_U32              0x31514C4BU
#define KLQ_PROTOCOL_VERSION       0x0001U
#define KLQ_HEADER_SIZE            16U
#define KLQ_MAX_PAYLOAD            132U
#define KLQ_MAX_FRAME_SIZE         (KLQ_HEADER_SIZE + KLQ_MAX_PAYLOAD)
#define KLQ_RESPONSE_BIT           0x8000U

enum {
    KLQ_CMD_INFO = 0x0001U,
    KLQ_CMD_ECHO = 0x0006U,
    KLQ_CMD_RESET = 0x0007U,
    KLQ_CMD_BOOT_HOLD = 0x0009U,
    KLQ_CMD_GET_SAMPLE = 0x0101U,
    KLQ_CMD_SET_CONFIG = 0x0102U,
    KLQ_CMD_GET_STATUS = 0x0103U,
    KLQ_CMD_SELF_TEST = 0x0104U,
    KLQ_CMD_ENTER_BOOTLOADER = 0x01F0U
};

enum {
    KLQ_STATUS_OK = 0U,
    KLQ_STATUS_BAD_COMMAND = 1U,
    KLQ_STATUS_BAD_LENGTH = 2U,
    KLQ_STATUS_BAD_CRC = 3U,
    KLQ_STATUS_BUSY = 4U,
    KLQ_STATUS_NOT_SUPPORTED = 5U,
    KLQ_STATUS_INTERNAL_ERROR = 6U
};

#endif
